const NEPALI_PARTS = Object.entries(NEPALI)
  .filter(([source, target]) => source.length > 1 && source !== target)
  .sort(([a], [b]) => b.length - a.length);

function escapeRegExp(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export function translate(language: Language, source: string): string {
  if (language === "en") return source;
  const trimmed = source.trim();
  const normalized = trimmed.replace(/\s+/g, " ");
  const translated = NEPALI[normalized];
  return translated ? source.replace(trimmed, translated) : source;
}

export function translateInterface(language: Language, source: string): string {
  const exact = translate(language, source);
  if (language === "en" || exact !== source) return exact;
  const trimmed = source.trim();
  const normalized = trimmed.replace(/\s+/g, " ");
  // Explicit translation boundaries may contain live values, for example
  // "3 students" or "Manage assignments for Ram". Translate the known UI
  // phrases around those values while leaving names and stored records intact.
  let composed = normalized;
  for (const [part, replacement] of NEPALI_PARTS) {
    const startsWithWord = /^[\p{L}\p{N}]/u.test(part);
    const endsWithWord = /[\p{L}\p{N}]$/u.test(part);
    const pattern = `${startsWithWord ? "(?<![\\p{L}\\p{N}])" : ""}${escapeRegExp(part)}${endsWithWord ? "(?![\\p{L}\\p{N}])" : ""}`;
    composed = composed.replace(new RegExp(pattern, "gu"), replacement);
  }
  return composed === normalized ? source : source.replace(trimmed, composed);
}
